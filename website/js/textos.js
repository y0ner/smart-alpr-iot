/**
 * Formatea una cadena del diccionario sustituyendo marcadores {clave}.
 */
export function traducir(idioma, clave, params = {}) {
  const tabla = TEXTOS[idioma] || TEXTOS.es;
  let plantilla = tabla[clave] ?? clave;
  for (const [k, v] of Object.entries(params)) {
    plantilla = plantilla.replaceAll(`{${k}}`, String(v));
  }
  return plantilla;
}
